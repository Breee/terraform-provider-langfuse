package scripts

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/hashicorp/hcl/v2"
	"github.com/hashicorp/hcl/v2/hclsyntax"
	frameworkprovider "github.com/hashicorp/terraform-plugin-framework/provider"
	"github.com/hashicorp/terraform-plugin-framework/resource"
	"github.com/langfuse/terraform-provider-langfuse/provider"
)

func TestGeneratedResourceDocumentation(t *testing.T) {
	ctx := context.Background()
	p := provider.New("test")()
	for _, factory := range p.Resources(ctx) {
		r := factory()
		metadata := resource.MetadataResponse{}
		r.Metadata(ctx, resource.MetadataRequest{ProviderTypeName: "langfuse"}, &metadata)
		t.Run(metadata.TypeName, func(t *testing.T) {
			schema := resource.SchemaResponse{}
			r.Schema(ctx, resource.SchemaRequest{}, &schema)
			if schema.Diagnostics.HasError() || strings.TrimSpace(schema.Schema.Description) == "" {
				t.Fatal("resource must have a schema description")
			}
			page := filepath.Join("..", "docs", "resources", strings.TrimPrefix(metadata.TypeName, "langfuse_")+".md")
			doc, err := os.ReadFile(page)
			if err != nil {
				t.Fatal(err)
			}
			for _, text := range []string{"# generated by", "## Example Usage", "## Schema", schema.Schema.Description} {
				if !strings.Contains(string(doc), text) {
					t.Errorf("generated page missing %q", text)
				}
			}
			exampleDir := filepath.Join("..", "examples", "resources", metadata.TypeName)
			example := filepath.Join(exampleDir, "resource.tf")
			source, err := os.ReadFile(example)
			if err != nil {
				t.Fatal(err)
			}
			file, diags := hclsyntax.ParseConfig(source, example, hcl.InitialPos)
			if diags.HasErrors() {
				t.Fatal(diags.Error())
			}
			body, ok := file.Body.(*hclsyntax.Body)
			if !ok {
				t.Fatal("expected HCL syntax body")
			}
			declared := make(map[string]bool)
			for _, block := range body.Blocks {
				if block.Type == "variable" && len(block.Labels) == 1 {
					declared["var."+block.Labels[0]] = true
				}
				if block.Type == "resource" && len(block.Labels) == 2 {
					declared[block.Labels[0]+"."+block.Labels[1]] = true
				}
			}
			for _, block := range body.Blocks {
				for _, attr := range block.Body.Attributes {
					for _, ref := range attr.Expr.Variables() {
						if len(ref) < 2 {
							continue
						}
						name, ok := ref[1].(hcl.TraverseAttr)
						if !ok {
							t.Errorf("unsupported example reference %v", ref)
							continue
						}
						key := ref.RootName() + "." + name.Name
						if !declared[key] {
							t.Errorf("example references undeclared input or resource %q", key)
						}
					}
				}
			}
			found := false
			for _, block := range body.Blocks {
				if block.Type != "resource" || len(block.Labels) != 2 || block.Labels[0] != metadata.TypeName {
					continue
				}
				found = true
				for name, attr := range schema.Schema.Attributes {
					if attr.IsRequired() && block.Body.Attributes[name] == nil {
						t.Errorf("example missing required argument %q", name)
					}
					if !strings.Contains(string(doc), "`"+name+"`") {
						t.Errorf("generated page missing attribute %q", name)
					}
				}
				for name := range block.Body.Attributes {
					attr, exists := schema.Schema.Attributes[name]
					if !exists || (attr.IsComputed() && !attr.IsOptional()) {
						t.Errorf("example sets unsupported or read-only argument %q", name)
					}
				}
			}
			if !found {
				t.Error("example must contain the documented resource")
			}
			if _, supportsImport := r.(resource.ResourceWithImportState); supportsImport {
				if _, err := os.Stat(filepath.Join(exampleDir, "import.sh")); err != nil {
					t.Fatal("importable resource must have an import example:", err)
				}
				if !strings.Contains(string(doc), "## Import") {
					t.Error("generated page missing import instructions")
				}
			} else if !strings.Contains(string(doc), "Import is not supported") {
				t.Error("resource without import must document the limitation")
			}
		})
	}
	schema := frameworkprovider.SchemaResponse{}
	p.Schema(ctx, frameworkprovider.SchemaRequest{}, &schema)
	doc, err := os.ReadFile("../docs/index.md")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(doc), schema.Schema.Description) || !strings.Contains(string(doc), "## Authentication") {
		t.Error("provider overview must include its generated description and authentication guide")
	}
}
